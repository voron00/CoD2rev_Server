/*
==============
StringValue
==============
*/
int StringValue( char *str, int len )
{
	char string[8192];
	char *pC1, *pC2;
	int n;

	if ( len >= sizeof(string) )
	{
		CompileError(g_sourcePos, "max string length exceeded: \"%s\"", str);
		return 0;
	}

	pC1 = string;

	while ( len )
	{
		if ( *str != '\\' )
		{
			len--;
			*pC1++ = *str++;
			continue;
		}

		n = len - 1;

		if ( !n )
		{
			break;
		}

		pC2 = str + 1;

		if ( *pC2 == 'n' )
		{
			*pC1++ = '\n';
		}
		else if ( *pC2 == 'r' )
		{
			*pC1++ = '\r';
		}
		else
		{
			if ( *pC2 == 't' )
			{
				*pC1 = '\t';
			}
			else
			{
				*pC1 = *pC2;
			}

			pC1++;
		}

		len = n - 1;
		str = pC2 + 1;
	}

	*pC1 = 0;

	yylval.val.stringValue = SL_GetString_(string, g_parse_user);
	return 1;
}

